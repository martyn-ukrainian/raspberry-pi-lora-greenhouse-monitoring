// LOW = живлення подано. Протилежно до VBAT_CTRL нижче — саме через цю
// несиметрію тут колись стояв не той рівень.
#define VEXT_CTRL  36
#define LED_PIN    35

// ОДИН ґрунтовий канал, GPIO2.
//
// У v1 їх було три, і саме через це виник баг з power-budget.md (проблема 8):
// `medianOf3()` брала медіану по трьох каналах, з яких два непідключені. Пін,
// що висить, віддає не нуль, а ШУМ, тож медіана з (реальне, шум, шум)
// повертала реальне значення приблизно в половині випадків — це не втрата
// точності, а зіпсований замір.
//
// Тут медіана береться по ЧАСУ з одного каналу, тож повторити цю помилку
// нічим. Коли з'явиться другий сенсор — він поїде окремим полем пакета, а не
// в ту саму медіану.
#define SOIL_1     2

#define AIR_SDA    41
#define AIR_SCL    42

// VBAT на GPIO1 через дільник, керований GPIO37.
//
// GPIO1 НЕ ЗАЙМАТИ під сенсори, попри те що `firmware/README.md` радить його як
// вільний ADC-пін.
//
// Дільник вмикається ВИСОКИМ рівнем — протилежно до VEXT_CTRL. Перевірено на
// залізі 2026-08-23: CTRL=LOW -> 0 мВ, CTRL=HIGH -> 811 мВ = 3,97 В на комірці.
#define VBAT_ADC   1
#define VBAT_CTRL  37
#define VBAT_DIVIDER 4.9f
