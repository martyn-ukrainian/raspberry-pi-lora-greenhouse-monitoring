// Скільки відліків іде в пакет. Три — компроміс: при втраті одного лишаються
// два для медіани, при двох лишився б один без страховки.
#ifndef SOIL_SAMPLES
#define SOIL_SAMPLES 3
#endif

// Пауза між відліками. НЕ нуль: три `analogRead` поспіль виконуються за
// мікросекунди, і це не три виміри, а один, прочитаний тричі — шум ADC на
// такому масштабі корельований, і медіана з них нічого не прибирає.
//
// 50 мс — обережна оцінка, а не заміряне число. Чи достатньо цього для
// незалежності відліків, покаже розкид `soil_min`/`soil_max` на живих даних:
// у v1 при кроці 3,17 с він був ~1,74 одиниці. Якщо тут вийде помітно вужчим —
// відліки корельовані й крок треба збільшувати.
#ifndef SOIL_GAP_MS
#define SOIL_GAP_MS 50
#endif

// Скільки перших відліків викинути.
//
// Заміряно на живих даних: перший відлік циклу (на 76-87 мс від Vext) занижений
// на 22 одиниці — стабільно, у 442 бурстах із 442. Це не шум, а систематичний
// зсув в один бік, і в медіану його пускати не можна.
//
// Чому саме викидати, а не чекати: причина зсуву не встановлена. Це або сенсор
// не вийшов на полицю, або ADC не встоявся після холодного старту плати — дві
// гіпотези, які лікуються протилежно, а розрізнити їх нема на чому: між 0,087 с
// і 3,2 с у даних немає жодного відліку. Викидання працює в обох випадках.
#ifndef SOIL_DISCARD_FIRST
#define SOIL_DISCARD_FIRST 1
#endif

// Скільки тримати Vext до ПЕРШОГО зарахованого відліку.
//
// Головна невідома цієї прошивки, тому параметр, а не константа. Єдина точка,
// про яку ТОЧНО відомо, що сенсор на ній придатний — 3,2 с (позиція 1 старого
// бурста, зсув −1,57 проти −3,64 у того, що v1 реально писала в базу).
//
// Це найдорожчий рядок у прошивці: прогрів займає 72% вікна неспання, тобто
// коштує більше, ніж уся решта разом. Коли крива виходу сенсора буде знята,
// тут стане заміряне число.
#ifndef SOIL_WARMUP_MS
#define SOIL_WARMUP_MS 3000
#endif

// Крок кривої в діагностичному режимі SOIL_PROBE_MS. 25 мс, бо шукається саме
// момент зникнення зсуву, а перші сотні мілісекунд і є відповіддю.
#ifndef SOIL_PROBE_EVERY_MS
#define SOIL_PROBE_EVERY_MS 25
#endif

