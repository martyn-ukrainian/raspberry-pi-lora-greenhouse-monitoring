// greenhouse-node-v2 — вузол теплиці з коротким вікном неспання.
//
// Відмінність від `greenhouse-node-lowpower` рівно одна, і вона не в логіці, а
// в тому, ЯК вузол чекає.
//
//   було:  зміряв -> передав (0,86 с) -> delay(2,00 с) -> ... сім разів
//          вікно 21,7 с, з них ~18 с процесор крутиться на повній частоті,
//          не роблячи нічого
//
//   стало: зміряв N разів поспіль -> передав ОДИН раз -> спати
//          вікно ~4,2 с
//
// Це та сама хвороба, що була у сні (піни лишались виходами й живили сплячі
// мікросхеми), тільки в іншій фазі: питання не «що вузол робить», а «що він
// робить, поки чекає».
//
// ЧОМУ РОЗНОСИТИ ВІДЛІКИ ПО ВІКНУ НЕ ТРЕБА. Заміряно на опорному вузлі
// (docs/дослідження/оптимізація-вікна-семплювання.md): реальна зміна показника за 15 хвилин
// — 1,38 одиниці ADC, власний шум сенсора — 1,74. Тобто всередині двадцяти
// секунд сигналу просто нічому мінятись, і двосекундні паузи між відліками
// купували рівно нічого за 12 секунд неспання.
//
// ЧОГО НЕМА НАВМИСНО: OLED і стендові режими (AGRO_SCREEN_TRACE, SOIL_AB_TEST,
// SOIL_WARMUP_PROBE). Вони лишаються в `greenhouse-node-lowpower` — там і
// налагоджувати. Тут кожен зайвий пін це витік у сні, а кожна зайва мілісекунда
// коштує як 4000 секунд сну.
//
// Структура — у README. Тут лишився рівно один цикл вимірювання.

#include <Arduino.h>

#include "config.h"
#include "core/events.h"
#include "core/log.h"
#include "core/power.h"
#include "sensors/air.h"
#include "sensors/battery.h"
#include "sensors/soil.h"
#include "telemetry/packet.h"
#include "telemetry/radio_link.h"

// Уся робота живе в setup(): пробудження з deep sleep — це не продовження
// виконання, а скидання, тож loop() не викликається жодного разу. На відміну
// від v1, тут це не умовність — повторювати нема чого, цикл рівно один.
void setup() {
  // 240 МГц нема на чому витрачати: робота — це чекання сенсорів і ефіру.
  setCpuFrequencyMhz(80);

  LOG_BEGIN();

  // Спершу журнал — інакше перші ж logEvent() писали б у неініціалізований слот.
  initEventLog();
  logResetReason();

  // Vext живить ґрунтовий сенсор. З цієї миті йде відлік прогріву, тож усе, що
  // нижче, встигає ініціалізуватись ПАРАЛЕЛЬНО з ним, а не після нього.
  powerOnVext();
  delay(SENSOR_SETTLE_MS);

  airBegin();

#ifdef AIR_PROBE_MS
  // Діагностичний прогін: малює криву виходу датчика повітря й одразу спати.
  // Штатний цикл при цьому не виконується — це не бойовий режим.
  airProbe();
  enterDeepSleep();
#endif

#ifdef SOIL_PROBE_MS
  // Крива виходу ґрунтового сенсора. Радіо не піднімаємо навмисно: воно додало
  // б ~450 мс до старту, а нас цікавлять саме перші мілісекунди після Vext.
  soilProbe();
  enterDeepSleep();
#endif

  if (!radioBegin()) {
    // Радіо не піднялось — не крутимось з увімкненим живленням, а йдемо спати
    // до наступного циклу: інакше один збій з'їдає всю батарею.
    enterDeepSleep();
  }

  SoilBurst soil = readSoilBurst();
  int soilPercent = soilRawToPercent(soil.median);

  float airTemp = 0, airHum = 0;
  bool airOk = airRead(airTemp, airHum);
  float vbat = batteryVolts();

  String msg = buildPacket(soil, soilPercent, airOk, airTemp, airHum, vbat);
  if (radioTransmit(msg)) {
    // Прапорці доїхали — тільки тепер їх можна гасити. Одометр errSeq росте
    // далі, щоб сервер бачив повтори тієї самої помилки.
    rtcLog.errFlags = 0;
  }

  enterDeepSleep();
}

// СТРАХОВКА, а не заглушка.
//
// Пробудження з deep sleep — це ресет, а не продовження виконання: плата
// заходить у setup() заново, тож справжнім тілом циклу є він, а loop() при
// справній роботі недосяжний.
//
// Але «недосяжний» тримається лише на тому, що КОЖЕН вихід із setup()
// закінчується enterDeepSleep(). Якщо колись з'явиться шлях, який туди не
// заходить, керування провалиться сюди — і плата крутитиметься на 39,55 мА,
// висадивши банку приблизно за три доби. Мовчки: пакети при цьому йти
// перестануть, а причину доведеться шукати з нуля.
//
// Порожнє тіло перетворило б це на тиху втрату батареї. Виклик сну робить
// найгіршим наслідком один пропущений цикл.
void loop() {
  enterDeepSleep();
}
