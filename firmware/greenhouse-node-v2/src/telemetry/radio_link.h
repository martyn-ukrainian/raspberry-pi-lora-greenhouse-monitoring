#pragma once

#include <Arduino.h>

// Обгортка над SX1262. Існує не заради краси, а щоб об'єкт `radio` мав рівно
// одного власника: його потрібно і в `setup()` (передати), і в `power.cpp`
// (приспати перед сном), а глобальна змінна, видима звідусіль, — це той самий
// клас помилок, що вже коштував нам 0,94 мА.

// true — радіо піднялось. Потрібне рівно для того, щоб не писати
// EV_RADIO_SLEEP_FAIL на шляху, де radio.begin() вже провалився: там збій сну
// не новина, а наслідок, і в телеметрії він лише дублював би EV_LORA_INIT_FAIL.
bool radioIsReady();

// Піднімає SPI і чип на 868 МГц. При невдачі пише EV_LORA_INIT_FAIL.
bool radioBegin();

// true — пакет пішов. При невдачі пише EV_LORA_TX_FAIL.
bool radioTransmit(String &msg);

// ХОЛОДНИЙ сон SX1262 (sleep(false)): 160 нА замість 0,6-1,2 мкА теплого.
// Втрата конфігурації нічого не коштує, бо deep sleep — це холодний старт усієї
// плати, і радіо однаково піднімається заново щоцикл.
//
// Код повернення НЕ відкидається. Якщо чип був зайнятий і команда не пройшла,
// він лишається в standby — сотні мікроампер замість одиниць, тобто мовчазна
// втрата половини ресурсу батареї. Тепер це приїде в телеметрії.
void radioSleep();
