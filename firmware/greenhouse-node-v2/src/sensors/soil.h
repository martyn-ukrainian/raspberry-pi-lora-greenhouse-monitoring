#pragma once

#include <Arduino.h>

#include "config.h"

// Результат бурста.
//
// Медіана — те, що піде в шкалу; min/max — розкид, заради якого бурст узагалі
// існує. Один відлік нема з чим порівняти: викид від наводки не відрізнити від
// справжньої зміни вологості, і саме він лишиться в історії назавжди.
//
// firstAtMs дає розкид ще й у часі: поки він їде в пакеті, прогрів не ховається
// за мовчазною константою, і межу можна буде підібрати з поля, а не зі стенду.
struct SoilBurst {
  int median;
  int minimum;
  int maximum;
  int count;
  unsigned long firstAtMs;  // від подачі Vext
};

// Витримує прогрів, викидає SOIL_DISCARD_FIRST перших відліків, знімає
// SOIL_SAMPLES з кроком SOIL_GAP_MS. При виході медіани за правдоподібні межі
// пише EV_SOIL_RANGE.
SoilBurst readSoilBurst();

// Сире ADC -> відсоток. Логарифм, а не map(): відгук сенсора експоненційний,
// і лінійна шкала з'їдає всю мокру половину діапазону.
int soilRawToPercent(int raw);

