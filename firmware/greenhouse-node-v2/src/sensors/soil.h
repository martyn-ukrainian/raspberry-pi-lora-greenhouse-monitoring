//
// Закриває найдорожчу невідому прошивки. Перший відлік циклу (на 87 мс)
// занижений на 21,66 одиниці — стабільно, у 442 бурстах із 442, жодного разу
// не в інший бік. Другий відлік, на 3,2 с, уже чистий. Що між ними — невідомо:
// у зібраних даних там НЕМАЄ ЖОДНОЇ ТОЧКИ, бо в v1 такт задавала передача.
//
