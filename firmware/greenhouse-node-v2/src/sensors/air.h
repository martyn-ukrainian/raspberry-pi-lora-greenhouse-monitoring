#pragma once

#include <Arduino.h>

// SHT31: температура й вологість повітря по I2C.
//
// Сенсор свідомо лишається на ПОСТІЙНИХ 3V3, а не на Vext: у спокої він їсть
// ~0,2 мкА (на тлі 10 мкА сну плати — ніщо), зате завжди перебуває в рівновазі
// з повітрям, і перший же замір після пробудження коректний. Якщо давати
// живлення імпульсами, датчик вологості щоразу заново врівноважується із
// середовищем, а це вже хвилини.

// Піднімає шину й перевіряє наявність сенсора. При відсутності пише
// EV_I2C_FAIL — це інша поломка, ніж NAN при читанні (обрив шлейфа проти збою
// самого сенсора), тому й код інший.
void airBegin();

// true — прочитали. false — сенсор мовчить після повторів, значення НЕ
// визначені, і в пакет вони не потрапляють.
//
// Порожні поля, а не нулі: раніше сюди писалось 0.0, і нулі йшли в ефір як
// звичайний вимір — сервер клав 0 °C у базу й будував на них алерти.
bool airRead(float &temp, float &hum);

#ifdef AIR_PROBE_MS
// ДІАГНОСТИКА, не бойовий режим. Друкує в Serial криву "ms,T,RH" від подачі
// Vext протягом AIR_PROBE_MS мілісекунд.
//
// Питання, на яке вона відповідає: чи можна перенести SHT31 з постійних 3V3 на
// комутований `Ve`. Модуль їсть ~1 мА цілодобово (заміряно 31.08.2026) — це
// 80% усього бюджету вузла, більше за все інше разом. Але `power-budget.md`
// стверджує, що імпульсне живлення псує вологість, бо датчик «щоразу заново
// врівноважується із середовищем».
//
// Твердження не перевірялось. Ця крива його перевіряє, і робить це ПАРНО:
// спершу знімається з сенсором на 3V3 (він не вимикався — базова лінія), потім
// той самий прогін з VCC, перекинутим на `Ve`. Різниця між кривими і є ефект
// вимикання живлення; усе інше в експерименті незмінне.
//
// Дивитись треба на ПЕРШІ значення проти усталених: якщо на 3V3 крива рівна з
// першої мілісекунди, а на `Ve` вологість повзе — твердження підтвердилось.
void airProbe();
#endif
