"""
Центральна конфігурація серверу agro.

Значення завантажуються з файлу `.env` (через pydantic-settings)
і можуть бути перевизначені реальними змінними середовища (`os.environ`).
Пріоритет: змінні середовища > `.env` > дефолти в цьому файлі.

Що ВХОДИТЬ сюди:
    - URL зовнішніх сервісів (база, Telegram API, webhook-и)
    - Секрети (токени, ключі, паролі)
    - Порти й хости
    - Рівень логгінгу (INFO / DEBUG / WARNING)
    - Робочі пороги, які оператор може захотіти підправити
      (алертні межі температури, вологості повітря, вологості ґрунту)

Що НЕ входить сюди:
    - Runtime-обʼєкти (engine, app, роутери, логгери) — вони живуть
      у своїх модулях і будуються ЗІ значень з settings.
    - Ідентичність системи (SERVICE_NAME, VERSION) — це частина коду,
      не конфіг.
    - Магічні числа з чистим кодовим змістом (HTTP-статуси, SECONDS_IN_HOUR).
    - Класи-моделі даних (Measurement, User, тощо).

Правило великого пальця:
    "Чи захоче оператор змінити це без правки коду —
     через `.env` на Raspberry Pi?"
        Так → сюди.
        Ні  → лишити модульною константою там де використовується.
"""

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    # extra="ignore" — бо `.env` на Pi спільний для кількох програм, а не лише
    # для цього класу. `node_forwarder.py` читає звідти NODES_INGEST_URL і
    # NODES_TOKEN напряму через os.environ, і вимагати, щоб кожен ключ файлу
    # був оголошений ТУТ, означає зв'язати незалежні програми через модель
    # однієї з них.
    #
    # Куплено дорого: 2026-08-24 о 23:23 ці два ключі додали в .env, і pydantic
    # (за замовчуванням extra="forbid") почав валити Settings на імпорті. Але
    # процеси вже працювали зі старим конфігом у пам'яті й нічого не помітили —
    # сервер помер аж о 09:24 наступного дня, при першому перезапуску, і не
    # піднявся. 6,5 години телеметрії не записано, причому вузли весь цей час
    # справно передавали.
    #
    # Ціна рішення: помилка в імені справжнього налаштування (SEVER_URL замість
    # SERVER_URL) тепер не викличе помилки, а тихо візьме дефолт. Це гірше за
    # гучне падіння — але краще за повну зупинку збору даних через ключ, який
    # цьому класу взагалі не адресований.
    model_config = SettingsConfigDict(
        env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )

    database_url: str = "sqlite:///agro.db"

    telegram_token: str
    telegram_chat_id: str

    server_url: str = "http://127.0.0.1:8000"
    serial_port: str = "/tmp/agro_adapter"
    gateway_port: str = "/tmp/agro_gateway"
    baudrate: int = 115200

    # Звідки адаптер бере потік шлюза: "serial" (USB) або "tcp" (мережа).
    # Причина існування другого варіанту прозаїчна: шнур, яким плата
    # під'єднана до Pi, зарядний — ліній даних у ньому нема, тому USB-тракт
    # непрацездатний фізично. Формат потоку в обох випадках той самий NDJSON.
    gateway_source: str = "serial"
    gateway_tcp_host: str = "0.0.0.0"
    gateway_tcp_port: int = 9009


settings = Settings()
